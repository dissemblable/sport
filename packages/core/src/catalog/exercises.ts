import {
  ROLE_CONTRIBUTION,
  type EquipmentCode,
  type ExerciseDefinition,
  type ExerciseMuscleInvolvement,
  type Mechanic,
  type MovementPattern,
  type MuscleCode,
  type ProgressionAxis,
} from '@sport/shared';

/**
 * Catalogue d'exercices réalisables à domicile.
 *
 * Contrainte absolue : chaque exercice n'utilise que du poids du corps, une
 * barre de traction, des haltères ou des élastiques. Aucun banc, aucune
 * machine, aucune barre olympique — le générateur ne peut proposer que ce que
 * l'utilisateur possède réellement.
 *
 * Chaque entrée porte trois informations décisives pour le moteur :
 *
 * - **La cartographie musculaire pondérée** : c'est elle qui alimente le calcul
 *   de fatigue. Un exercice mal cartographié fausse tout le suivi de
 *   récupération en aval.
 * - **La charge systémique** : deux exercices peuvent solliciter les mêmes
 *   muscles avec un coût global très différent (un pistol squat épuise
 *   l'organisme, une extension mollet non).
 * - **La famille de progression** : en l'absence de charges lourdes, progresser
 *   signifie souvent changer de variante plutôt que d'ajouter des kilos.
 */

/** Muscle seul (contribution par défaut du rôle) ou couple [muscle, contribution]. */
type MuscleSpec = MuscleCode | readonly [MuscleCode, number];

interface ExerciseSeed {
  slug: string;
  name: string;
  pattern: MovementPattern;
  mechanic: Mechanic;
  /** 1 = accessible à tous, 5 = mouvement avancé. */
  difficulty: number;
  equipment: EquipmentCode[];
  primary: MuscleSpec[];
  secondary?: MuscleSpec[];
  stabilizers?: MuscleSpec[];
  reps: readonly [number, number];
  restSeconds?: number;
  /** Coût systémique relatif (0,5 à 1,5). Défaut : 1,0 en poly, 0,7 en isolation. */
  systemicLoad?: number;
  isUnilateral?: boolean;
  axes?: ProgressionAxis[];
  /** Famille de progression : chaîne les variantes de la plus facile à la plus dure. */
  family?: string;
  rank?: number;
  setup?: string;
  cues: string[];
}

function toInvolvement(
  specs: MuscleSpec[] | undefined,
  role: 'primary' | 'secondary' | 'stabilizer',
): ExerciseMuscleInvolvement[] {
  if (!specs) return [];
  return specs.map((spec) => {
    const [muscle, contribution] = Array.isArray(spec)
      ? (spec as readonly [MuscleCode, number])
      : ([spec as MuscleCode, ROLE_CONTRIBUTION[role]] as const);
    return { muscle, role, contribution };
  });
}

function buildCatalog(seeds: ExerciseSeed[]): ExerciseDefinition[] {
  return seeds.map((seed, index) => {
    const isCompound = seed.mechanic === 'compound';
    const muscles = [
      ...toInvolvement(seed.primary, 'primary'),
      ...toInvolvement(seed.secondary, 'secondary'),
      ...toInvolvement(seed.stabilizers, 'stabilizer'),
    ];

    return {
      id: index + 1,
      slug: seed.slug,
      name: seed.name,
      pattern: seed.pattern,
      mechanic: seed.mechanic,
      difficulty: seed.difficulty,
      isUnilateral: seed.isUnilateral ?? false,
      systemicLoad: seed.systemicLoad ?? (isCompound ? 1.0 : 0.7),
      equipment: seed.equipment,
      muscles,
      defaultRepMin: seed.reps[0],
      defaultRepMax: seed.reps[1],
      defaultRestSeconds: seed.restSeconds ?? (isCompound ? 120 : 75),
      progressionAxes: seed.axes ?? ['reps', 'load'],
      progressionFamily: seed.family ?? null,
      progressionRank: seed.rank ?? 1,
      setupNotes: seed.setup ?? null,
      executionCues: seed.cues,
    } satisfies ExerciseDefinition;
  });
}

