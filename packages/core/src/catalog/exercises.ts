/**
 * Chaînes de progression : pour chaque famille, les variantes ordonnées de la
 * plus facile à la plus difficile. Utilisé pour proposer la marche suivante
 * quand un exercice devient trop facile (ou trop dur).
 */
export function getProgressionFamily(family: string): ExerciseDefinition[] {
  return EXERCISE_CATALOG.filter((e) => e.progressionFamily === family).sort(
    (a, b) => a.progressionRank - b.progressionRank,
  );
}
